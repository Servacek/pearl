local OUTPUT_FILE_PATH = PEARL.SRCDIR.."/constants/generated/emoji_data.lua"
local EMOJIS = PEARL.loadfile("constants/emojis")

local CustomDataDumper = PEARL.loadfile("utils/datadumper", nil, true)


local emoji_data_list = PEARL.loadfile("constants/generated/emoji_data", nil, true, function(...)
    PEARL.error(...)
end) or {}


for name, utf8_str in pairs(EMOJIS.ALL) do
    local id = PEARL.EMOJIS.NAME_TO_INPUTTYPE[name] or name

    -- New emoji detected!
    local data = emoji_data_list[id]
    if data == nil then
        PEARL.info("Adding new emoji", name, id)

        emoji_data_list[id] = {
            name = name,
            id = id,
            utf8_str = utf8_str,
            timecreated = os.time(),
        }
    else
        if data.name ~= name then
            if EMOJIS.ALL[data.name] == nil then
                data.name = name
            end
        else
            PEARL.warn("Alias detected in definition file!", data.name)
        end
    end
end

local output_file, errmsg = io.open(OUTPUT_FILE_PATH, "w")
if not output_file then
    return PEARL.error("Failed to load the emoji data output file!", errmsg)
end

local output = CustomDataDumper(emoji_data_list, nil, false, nil, true)
output = output:gsub("([%S]*time[%S]*%s*=%s*)(%d+),?([^\n]*)", function(rest_left, timestamp_string, rest_right)
    local timestamp = tonumber(timestamp_string)
    if not timestamp then
        return
    end

    return rest_left..timestamp_string..","..rest_right.." -- "..os.date("%c", timestamp)
end)
output_file:write("-- This file was automatically generated by emojidatagenerator.lua\n")
output_file:write("\n")
output_file:write(output)

PEARL.info("Successfully saved data to ", OUTPUT_FILE_PATH)
